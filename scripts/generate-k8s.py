def inbound_svc_yaml(c: Ctx) -> str:
    """Stable VIP for gear that cannot follow DNS. LoadBalancer mode only."""
    if c.mode != "loadbalancer":
        return ""
    policy = "Local" if c.preserve_src else "Cluster"
    lb = ""
    if c.lb_ip:
        lb = f"  loadBalancerIP: {c.lb_ip}\n"
    ports = [
        "    - name: netflow\n      port: 9995\n      protocol: UDP\n      targetPort: 9995",
        "    - name: syslog-udp\n      port: 1514\n      protocol: UDP\n      targetPort: 1514",
        "    - name: syslog-tcp\n      port: 1514\n      protocol: TCP\n      targetPort: 1514",
    ]
    seen = {"9995", "1514"}
    for g in c.groups:
        if not is_poller(g):
            continue
        trap = g["TRAP_PORT"]
        if trap in seen:
            continue
        seen.add(trap)
        ports.append(
            f"    - name: traps-{g['GROUP']}\n      port: {trap}\n      protocol: UDP\n      targetPort: {trap}"
        )
    # One Service cannot select multiple Deployments. Use a shared label.
    # Collectors in LB mode get app.kubernetes.io/inbound: "true" — added below
    # by patching would be messy; instead expose each listener as its own Service
    # sharing the same loadBalancerIP (MetalLB) or document per-Service IPs.
    #
    # Cloud LBs often want one IP per Service. We emit *one* Service per
    # listener so operators can attach the same reserved IP annotation/vendor
    # config, and we also emit a cheat-sheet ConfigMap.
    docs = []
    selectors = [
        ("ktranslate-inbound-flow", "ktranslate-flow", ports[0]),
        ("ktranslate-inbound-syslog", "ktranslate-syslog", "\n".join(ports[1:3])),
    ]
    for g in c.groups:
        if not is_poller(g):
            continue
        trap = g["TRAP_PORT"]
        selectors.append(
            (
                f"ktranslate-inbound-traps-{g['GROUP']}",
                f"ktranslate-snmp-{g['GROUP']}",
                f"    - name: traps\n      port: {trap}\n      protocol: UDP\n      targetPort: {trap}",
            )
        )
    for svc_name, app, port_block in selectors:
        docs.append(
            f"""apiVersion: v1
kind: Service
metadata:
  name: {svc_name}
  namespace: {c.ns}
  annotations:
    ktranstografana/collector-ip: "{c.lb_ip or "SET-K8S-LOADBALANCER-IP"}"
spec:
  type: LoadBalancer
  externalTrafficPolicy: {policy}
{lb}  selector:
    app: {app}
  ports:
{port_block}
"""
        )
    return "\n---\n".join(docs)


def pdb_yaml(c: Ctx) -> str:
    """Honest PDB: one replica, so a drain *will* drop UDP briefly."""
    names = ["alloy", "ktranslate-flow", "ktranslate-syslog", "flow-dns"]
    names += [f"ktranslate-snmp-{g['GROUP']}" for g in c.groups if is_poller(g)]
    docs = []
    for name in names:
        docs.append(
            f"""apiVersion: policy/v1
kind: PodDisruptionBudget
metadata:
  name: {name}
  namespace: {c.ns}
spec:
  maxUnavailable: 1
  selector:
    matchLabels:
      app: {name}
"""
        )
    return "\n---\n".join(docs)


def endpoints_md(c: Ctx) -> str:
    dest = c.collector_ip or c.lb_ip or (
        f"IP of node {c.node}" if c.node else "<SET K8S_COLLECTOR_IP>"
    )
    rows = [
        "| Signal | Stamp on the device | Notes |",
        "|--------|---------------------|-------|",
        f"| NetFlow / IPFIX / sFlow (`NF_SOURCE={c.nf_source}`) | `{dest}:9995` UDP | One listener. Do not replica this Deployment. |",
        f"| Syslog | `{dest}:1514` UDP/TCP | Privileged port — needs NET_BIND_SERVICE. |",
    ]
    for g in c.groups:
        if not is_poller(g):
            continue
        rows.append(
            f"| SNMP traps (`{g['GROUP']}`) | `{dest}:{g['TRAP_PORT']}` UDP | Poller is also the trap sink. |"
        )
    warns = []
    if c.mode == "hostnetwork" and not c.node:
        warns.append("- **Unpinned hostNetwork:** the destination IP changes if the pod moves.")
    if c.mode == "loadbalancer" and not c.lb_ip:
        warns.append("- **No reserved VIP:** the cloud LB address can change on recreate.")
    if not c.preserve_src and c.mode == "loadbalancer":
        warns.append("- **externalTrafficPolicy=Cluster:** source IPs are SNATed; flow/trap identity suffers.")
    warn_block = "\n".join(warns) if warns else "- Collector identity looks pinned (still verify the IP on the node/LB)."
    return f"""# Collector endpoints — stamp these IPs on network gear

Kubernetes DNS names are for **in-cluster** traffic (ktranslate → Alloy).
Devices typically **cannot** follow DNS. Use the IP below.

**Mode:** `{c.mode}` · **Node:** `{c.node or "unpinned"}` · **deployment.host:** `{c.host}`

{chr(10).join(rows)}

## Warnings

{warn_block}

Read [k8s/LIMITATIONS.md](../LIMITATIONS.md) before you scale replicas or
add a second collector "for HA".
"""


def kustomization(names: list[str]) -> str:
    res = "\n".join(f"  - {n}" for n in names)
    return f"""apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
{res}
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--skip-generate", action="store_true")
    args = ap.parse_args()

    dotenv = load_dotenv(REPO / ".env")
    dotenv.update({k: v for k, v in os.environ.items() if k.startswith("K8S_") or k in {
        "KTRANS_HOST", "KTRANSLATE_IMAGE", "ALLOY_IMAGE", "FLOW_DNS_IMAGE",
        "NF_SOURCE", "SYSLOG_SOURCE",
    }})

    group_files = sorted((REPO / "groups").glob("*.env"))
    if not group_files:
        raise SystemExit("no groups/*.env — copy a groups/*.env.sample first")
    groups = [parse_group_env(p) for p in group_files]

    if not args.skip_generate:
        try:
            run_generate_groups()
        except (subprocess.CalledProcessError, FileNotFoundError) as exc:
            print(f"WARN: generate-groups.sh failed ({exc}); using existing config/", file=sys.stderr)
            if not (REPO / "config" / "catalog.yaml").is_file():
                raise SystemExit("config/catalog.yaml missing and generate-groups.sh failed") from exc

    c = Ctx(dotenv, groups)
    if c.mode == "hostnetwork" and not c.node:
        print(
            "WARN: K8S_COLLECTOR_NODE is empty. hostNetwork pods can land on any "
            "node and the destination IP your gear has configured will go stale.",
            file=sys.stderr,
        )
    if c.mode == "loadbalancer" and not c.lb_ip:
        print(
            "WARN: K8S_LOADBALANCER_IP / K8S_COLLECTOR_IP is empty. "
            "The assigned VIP may be ephemeral.",
            file=sys.stderr,
        )

    files: list[tuple[str, str]] = [
        ("00-namespace.yaml", ns_yaml(c)),
        ("01-identity.yaml", identity_yaml(c)),
        ("02-pvc.yaml", pvc_yaml(c)),
        ("03-scripts.yaml", scripts_cm(c)),
        ("04-catalog.yaml", catalog_cm(c)),
        ("10-alloy.yaml", alloy_yaml(c)),
        ("20-flow-dns.yaml", flow_dns_yaml(c)),
        ("30-flow.yaml", flow_yaml(c)),
        ("40-syslog.yaml", syslog_yaml(c)),
        ("61-bootstrap.yaml", bootstrap_yaml(c)),
        ("80-pdb.yaml", pdb_yaml(c)),
    ]
    pollers = poller_cms(c)
    if pollers:
        files.append(("05-pollers.yaml", pollers))
    snmp = snmp_yaml(c)
    if snmp:
        files.append(("50-snmp.yaml", snmp))
    disco = discovery_yaml(c)
    if disco:
        files.append(("60-discovery.yaml", disco))
    files.sort(key=lambda t: t[0])
    inbound = inbound_svc_yaml(c)
    if inbound:
        files.append(("70-inbound-svc.yaml", inbound))

    names = [n for n, _ in files]
    files.append(("kustomization.yaml", kustomization(names)))

    if not args.dry_run:
        if OUT.exists():
            for old in OUT.glob("*.yaml"):
                old.unlink()
            ep = OUT / "COLLECTOR-ENDPOINTS.md"
            if ep.exists():
                ep.unlink()

    for name, body in files:
        write_out(name, body, args.dry_run)
    write_out("COLLECTOR-ENDPOINTS.md", endpoints_md(c), args.dry_run)

    print()
    print(f"namespace={c.ns} mode={c.mode} host={c.host} groups={len(c.groups)}")
    print("apply:  bash scripts/deploy-k8s.sh")
    print("read:   k8s/LIMITATIONS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
