#!/usr/bin/env python3
"""Render k8s/generated/ from the same groups/*.env as Compose.

This is another *runtime* for the KtransToGrafana workflow, not a fork:
  groups/*.env → make generate → poller/discovery/catalog YAML
               → this script → Kubernetes manifests

Usage:
  python3 scripts/generate-k8s.py
  python3 scripts/generate-k8s.py --dry-run
  python3 scripts/generate-k8s.py --skip-generate   # reuse existing config/

See k8s/LIMITATIONS.md before you point network gear at a cluster.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "k8s" / "generated"
SCRIPTS = REPO / "k8s" / "scripts"


def load_dotenv(path: Path) -> dict[str, str]:
    env: dict[str, str] = {}
    if not path.is_file():
        return env
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        env[k.strip()] = v.strip().strip('"').strip("'")
    return env


def parse_group_env(path: Path) -> dict[str, str]:
    data = load_dotenv(path)
    role = (data.get("ROLE") or "both").strip().lower() or "both"
    required = ["GROUP"]
    if role != "discover":
        required.extend(("METALISTEN_PORT", "TRAP_PORT"))
    missing = [k for k in required if not data.get(k)]
    if missing:
        raise SystemExit(f"{path.name}: missing {', '.join(missing)}")
    return data


def group_role(g: dict[str, str]) -> str:
    return (g.get("ROLE") or "both").strip().lower() or "both"


def is_poller(g: dict[str, str]) -> bool:
    return group_role(g) in {"poll", "both"}


def is_discoverer(g: dict[str, str]) -> bool:
    return group_role(g) in {"discover", "both"}


def run_generate_groups() -> None:
    script = REPO / "scripts" / "generate-groups.sh"
    subprocess.run(["bash", str(script)], cwd=REPO, check=True)


def ktrans_host(dotenv: dict[str, str]) -> str:
    explicit = dotenv.get("KTRANS_HOST", "").strip()
    if explicit:
        return explicit
    try:
        return subprocess.check_output(
            ["bash", str(REPO / "scripts" / "host-id.sh")],
            cwd=REPO,
            text=True,
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return os.uname().nodename.split(".")[0]


def indent(text: str, n: int = 4) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else "" for line in text.rstrip().splitlines())


def header() -> str:
    return (
        "# GENERATED by scripts/generate-k8s.py — do not edit by hand.\n"
        "# Re-run: make generate-k8s\n"
    )


def write_out(name: str, body: str, dry_run: bool) -> None:
    # kustomize rejects a comment-only first document; keep kustomization.yaml bare.
    prefix = "" if name == "kustomization.yaml" else header()
    content = prefix + body.lstrip() + ("\n" if not body.endswith("\n") else "")
    dest = OUT / name
    if dry_run:
        print(f"--- {dest.name} ({len(content)} bytes)")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    dest.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {dest.relative_to(REPO)}")


def read_script(name: str) -> str:
    path = SCRIPTS / name
    if not path.is_file():
        raise SystemExit(f"missing {path}")
    return path.read_text(encoding="utf-8")


class Ctx:
    def __init__(self, dotenv: dict[str, str], groups: list[dict[str, str]]) -> None:
        self.env = dotenv
        self.groups = groups
        self.ns = dotenv.get("K8S_NAMESPACE", "ktrans") or "ktrans"
        self.mode = (dotenv.get("K8S_INGRESS_MODE") or "hostnetwork").strip().lower()
        if self.mode not in {"hostnetwork", "loadbalancer"}:
            raise SystemExit("K8S_INGRESS_MODE must be hostnetwork or loadbalancer")
        self.node = (dotenv.get("K8S_COLLECTOR_NODE") or "").strip()
        self.collector_ip = (dotenv.get("K8S_COLLECTOR_IP") or "").strip()
        self.lb_ip = (dotenv.get("K8S_LOADBALANCER_IP") or self.collector_ip).strip()
        self.preserve_src = (dotenv.get("K8S_PRESERVE_SOURCE_IP") or "1").strip() not in {
            "0",
            "false",
            "no",
        }
        self.alloy_mode = (dotenv.get("K8S_ALLOY_MODE") or "cluster").strip().lower()
        if self.alloy_mode not in {"cluster", "hostnetwork"}:
            raise SystemExit("K8S_ALLOY_MODE must be cluster or hostnetwork")
        self.storage_class = (dotenv.get("K8S_STORAGE_CLASS") or "").strip()
        self.storage_size = (dotenv.get("K8S_STORAGE_SIZE") or "1Gi").strip()
        self.discover_sched = (dotenv.get("K8S_DISCOVER_SCHEDULE") or "0 */6 * * *").strip()
        self.ktranslate = dotenv.get("KTRANSLATE_IMAGE") or "quay.io/kentik/ktranslate:latest"
        self.alloy = dotenv.get("ALLOY_IMAGE") or "grafana/alloy:latest"
        self.flow_dns = dotenv.get("FLOW_DNS_IMAGE") or "andyshinn/dnsmasq:2.83"
        self.yq = dotenv.get("K8S_YQ_IMAGE") or "mikefarah/yq:4"
        self.busybox = dotenv.get("K8S_BUSYBOX_IMAGE") or "busybox:1.36"
        self.nf_source = dotenv.get("NF_SOURCE") or "auto"
        self.syslog_source = dotenv.get("SYSLOG_SOURCE") or "0.0.0.0:1514"
        self.host = ktrans_host(dotenv)
        self.host_network = self.mode == "hostnetwork"
        if self.alloy_mode == "hostnetwork":
            self.otel = "http://127.0.0.1:4317/"
        else:
            self.otel = f"http://alloy.{self.ns}.svc.cluster.local:4317/"
        self.dns = f"flow-dns.{self.ns}.svc.cluster.local:53"

    def otel_name(self, base: str) -> str:
        return f"{base}-{self.host}" if self.host else base

    def node_selector(self, n: int = 6) -> str:
        if not self.node:
            return ""
        pad = " " * n
        return (
            f"{pad}nodeSelector:\n"
            f"{pad}  kubernetes.io/hostname: {self.node}\n"
        )

    def host_net_spec(self, n: int = 6) -> str:
        if not self.host_network:
            return self.node_selector(n)
        pad = " " * n
        return (
            f"{pad}hostNetwork: true\n"
            f"{pad}dnsPolicy: ClusterFirstWithHostNet\n"
            f"{self.node_selector(n)}"
        )

    def recreate(self) -> str:
        return "  strategy:\n    type: Recreate\n"

    def ktrans_env(self, service_base: str) -> str:
        return f"""          env:
            - name: OTEL_SERVICE_NAME
              value: {self.otel_name(service_base)}
            - name: OTEL_EXPORTER_OTLP_COMPRESSION
              value: gzip
            - name: AWS_REGION
              valueFrom:
                secretKeyRef:
                  name: ktrans-optional
                  key: AWS_REGION
                  optional: true
            - name: AWS_ACCESS_KEY_ID
              valueFrom:
                secretKeyRef:
                  name: ktrans-optional
                  key: AWS_ACCESS_KEY_ID
                  optional: true
            - name: AWS_SECRET_ACCESS_KEY
              valueFrom:
                secretKeyRef:
                  name: ktrans-optional
                  key: AWS_SECRET_ACCESS_KEY
                  optional: true
            - name: AWS_SESSION_TOKEN
              valueFrom:
                secretKeyRef:
                  name: ktrans-optional
                  key: AWS_SESSION_TOKEN
                  optional: true"""


